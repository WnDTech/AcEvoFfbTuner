using System.Runtime.InteropServices;
using AcEvoFfbTuner.Core.DeviceDetection;

namespace AcEvoFfbTuner.Core.FfbProviders;

/// <summary>
/// TrueForce stream FFB provider for Logitech direct-drive wheels (RS50, G PRO).
///
/// The RS50/G PRO expose two independent force transports:
///   1. HID++ feature 0x8123 (set-and-hold motor target) — what Logitech's
///      runtime and DirectInput PID effects use. While a TrueForce session
///      is active its stream force OVERRIDES this path, which is why the
///      app's DI force works in TEST but is dead in-game.
///   2. The TrueForce stream (interface 2, usage page 0xFFFD, 64-byte
///      output reports, report ID 0x01) — what AC EVO / ACC stream through
///      natively. This provider writes the SAME channel, so the app becomes
///      the FFB source — no G HUB, no PC-mode dependency.
///
/// Packet layout (force-only subset, byte 10 = 0 — pure "cur" torque
/// target, no audio window):
///     byte 0     0x01          HID report ID
///     bytes 1-3  0x00          reserved
///     byte 4     0x01          command type (stream/sample packet)
///     byte 5     seq           u8 session counter, wraps at 255
///     bytes 6-7  u16 LE        "cur" = motor torque target (offset binary)
///     bytes 8-9  u16 LE        duplicate of 6-7 (must match)
///     byte 10    0x00          new-sample count (0 = pure force command)
///     bytes 11-63 0x00         zero for a constant-force packet
///
/// Force encoding: offset binary, (int16)signed + 0x8000; 0x8000 = neutral.
///
/// Init: the 68-packet sequence captured from G HUB (mescon driver,
/// tf_init_data.h) is replayed TWICE, seq restarted at 1 per pass, 2 ms
/// apart — two-pass init replicates G HUB and is more reliable on cold
/// boot. The type-0x0e packet carries the operating range as float32 LE
/// degrees and is rewritten with the wheel's actual rotation so the init
/// never resets the range (the 90°/2700° reset bug).
///
/// Stream pump: 1 kHz thread (timeBeginPeriod(1), Highest priority).
/// Set-and-hold: the wheel holds the last "cur" indefinitely, so pausing
/// the stream for HID++ settings reads is safe.
///
/// Sign convention: verified by TF4ALL on real hardware — the game-FFB
/// channel (HID++ 0x8123 / DI) and ep3 "cur" use OPPOSITE signs, so the
/// force is negated by default (ForceInvert). Everything is logged to
/// logitech_trueforce.log.
/// </summary>
public sealed class LogitechTrueForceProvider : IFFBProvider
{
    #region Protocol constants

    private const int PacketLen = 64;
    private const int SeqOffset = 5;
    private const int TypeOffset = 4;
    private const int RangeType = 0x0E;
    private const int RangeOffset = 6;
    private const int InitPacketCount = 68;
    private const int InitInterPacketUs = 2000;
    // The wheel accepts 250-1000 Hz. 1 kHz made the TrueForce amplifier emit a
    // constant audible "bee" carrier tone (user-verified); 500 Hz is more than
    // enough for force (the game's own HID++ FFB runs at 140-333 Hz).
    private const int StreamHz = 500;
    private const int MaxConsecutiveWriteFails = 250;

    private const ushort LogitechVid = 0x046D;

    // RS50 native / compat, G PRO (Xbox/PC + PS/PC), G923 (PS + Xbox editions)
    // — same list as LogitechHidppWheelProvider.
    private static readonly ushort[] SupportedPids = [0xC276, 0xC272, 0xC268, 0xC266, 0xC267, 0xC26D, 0xC26E];

    #endregion

    #region Native interop

    [DllImport("kernel32.dll", CharSet = CharSet.Auto, SetLastError = true)]
    private static extern IntPtr CreateFile(string path, uint access, uint share, IntPtr sec, uint disposition, uint flags, IntPtr template);

    [DllImport("kernel32.dll", SetLastError = true)]
    private static extern bool CloseHandle(IntPtr h);

    [DllImport("kernel32.dll", SetLastError = true)]
    private static extern bool WriteFile(IntPtr h, byte[] buf, int len, out int written, IntPtr overlapped);

    [DllImport("hid.dll", SetLastError = true)]
    private static extern bool HidD_SetOutputReport(IntPtr dev, byte[] buf, int len);

    [DllImport("winmm.dll", EntryPoint = "timeBeginPeriod")]
    private static extern uint TimeBeginPeriod(uint period);

    [DllImport("winmm.dll", EntryPoint = "timeEndPeriod")]
    private static extern uint TimeEndPeriod(uint period);

    private const uint GENERIC_READ = 0x80000000;
    private const uint GENERIC_WRITE = 0x40000000;
    private const uint FILE_SHARE_RW = 0x03;
    private const uint OPEN_EXISTING = 3;

    private static readonly IntPtr InvalidHandle = new(-1);

    #endregion

    private readonly string _logPath;
    private IntPtr _handle = InvalidHandle;
    private string _devicePath = "";
    private string _productName = "";
    private Thread? _pumpThread;
    private volatile bool _running;
    private volatile bool _disposed;
    private volatile bool _paused;
    private volatile float _targetNorm;
    private byte _seq;
    private long _packetsSent;
    private long _packetsFailed;
    private int _consecutiveFails;
    private float _smoothedLsb;
    private bool _hapticsNoted;

    public LogitechTrueForceProvider()
    {
        _logPath = Path.Combine(
            Environment.GetFolderPath(Environment.SpecialFolder.ApplicationData),
            "AcEvoFfbTuner", "logitech_trueforce.log");
        Log("=== LogitechTrueForceProvider created ===");
    }

    // ── IFFBProvider ──────────────────────────────────────────────────────

    public string ProviderName => "Logitech TrueForce (Stream)";
    public bool IsInitialized { get; private set; }
    public bool IsAvailable => _handle != InvalidHandle && IsInitialized;
    public string? LastError { get; private set; }

    /// <summary>True while the stream pump is paused (HID++ settings reads).</summary>
    public bool IsPaused => _paused;
    public string ProductName => _productName;
    public long PacketsSent => Interlocked.Read(ref _packetsSent);
    public long PacketsFailed => Interlocked.Read(ref _packetsFailed);

    // ── Tuning (defaults verified by TF4ALL / mescon on real RS50 hardware) ──

    /// <summary>Game-FFB channel (HID++ 0x8123 / DI) and ep3 "cur" use
    /// opposite signs — negate by default.</summary>
    public bool ForceInvert { get; set; } = true;

    /// <summary>Multiplier applied to the normalized force before LSB
    /// conversion. 0.5 default: the TrueForce amplifier is stronger per-unit
    /// than the DI path, and full scale (1.0) was arm-ripping on the user's
    /// wheel at 35% test force.</summary>
    public float ForceScale { get; set; } = 0.5f;

    /// <summary>IIR low-pass time constant (ms) on the force target before
    /// it goes into "cur". 0 = none (sample-and-hold).</summary>
    public float SmoothTimeConstantMs { get; set; } = 1.0f;

    /// <summary>Operating range in degrees, patched into the type-0x0e init
    /// packet so the init never resets the wheel's range (90°/2700° bug).
    /// Range 90-2700; values outside are left at the captured 2700.
    /// Assigning a valid value marks the range as known — the pump thread
    /// waits up to <see cref="RangeWaitMs"/> for it so the init push is a
    /// no-op instead of a range sweep.</summary>
    private int _rotationDegrees = 1080;
    private volatile bool _rangeKnown;

    public int RotationDegrees
    {
        get => _rotationDegrees;
        set
        {
            if (value >= 90 && value <= 2700)
            {
                _rotationDegrees = value;
                _rangeKnown = true;
            }
        }
    }

    private const int RangeWaitMs = 2500;

    // ── Lifecycle ─────────────────────────────────────────────────────────

    public bool Initialize()
    {
        if (IsInitialized) return true;
        return ConnectAndStart();
    }

    public void UpdateTorque(float signal)
    {
        _targetNorm = Math.Clamp(signal, -1f, 1f);
    }

    public void SetHaptics(HapticData data)
    {
        // Force-only first step: the wheel's ep3 "cur" channel has no
        // separate vibration field — haptics would need to be summed into
        // cur or pushed through the 13-slot audio window (later iteration).
        if (!_hapticsNoted)
        {
            _hapticsNoted = true;
            Log($"SetHaptics: intensity={data.VibrationIntensity:F4} — vibration not yet mapped to the TrueForce stream (force-only step)");
        }
    }

    public void ZeroTorque()
    {
        _targetNorm = 0f;
    }

    public void Shutdown()
    {
        // Tear the TrueForce session down BEFORE closing the handle: an app
        // close without teardown leaves the wheel in a stale "session active"
        // state that overrides ALL force paths (DI, 0x8123, settings responses)
        // until the wheel is re-initialized or power-cycled (user-verified:
        // "No FFB again" after closing the app mid-session).
        //
        // Order matters: stop the pump FIRST so the session-end handshake can
        // never race the pump's init/stream writes (a teardown racing the init
        // sequence was observed in the field — the pump replayed the full
        // 68-packet init AFTER the handshake and the wheel ended up confused).
        StopPump();
        WriteTeardown();
        CloseStreamHandle();
        IsInitialized = false;
    }

    /// <summary>Neutral packet + the captured session-end handshake (init
    /// packets #67/#68: type 0x04 then 0x03) so the wheel releases the
    /// TrueForce session cleanly.</summary>
    private void WriteTeardown()
    {
        if (_handle == InvalidHandle) return;
        try
        {
            WriteNeutralPacket();

            // Packet #67 = type 0x04 (start/continue handshake), #68 = type 0x03 (stop).
            foreach (int idx in new[] { 66, 67 })
            {
                // Clone — InitPackets is shared with the pump's RunInitSequence
                // and the seq byte is mutated in place.
                byte[] pkt = (byte[])InitPackets[idx].Clone();
                pkt[SeqOffset] = (byte)((idx + 1) & 0xFF);
                if (!WritePacket(pkt))
                {
                    Log($"WriteTeardown: packet {idx + 1} write FAILED (err={Marshal.GetLastWin32Error()})");
                    break;
                }
                PrecisionSleepUs(InitInterPacketUs);
            }
            WriteNeutralPacket();
            Log("WriteTeardown: session-end handshake sent (neutral + 0x04/0x03)");
        }
        catch (Exception ex)
        {
            Log($"WriteTeardown: threw — {ex.GetType().Name}: {ex.Message}");
        }
    }

    public void Dispose()
    {
        if (_disposed) return;
        _disposed = true;
        Shutdown();
    }

    // ── HID++ settings coexistence ────────────────────────────────────────

    /// <summary>Pause the stream before HID++ settings reads (set-and-hold
    /// makes this safe). A neutral packet is written first so the wheel
    /// never holds a stale nonzero force during the read.</summary>
    public void Pause()
    {
        if (_paused) return;
        _paused = true;
        // Only write the neutral packet if the init sequence already ran —
        // before that the wheel's last commanded force is already neutral
        // (init ends on a type-0x01 neutral packet) and a pre-init sample
        // packet could confuse the session.
        if (IsInitialized)
            WriteNeutralPacket();
        Log("Paused for HID++ settings reads — neutral force held");
    }

    public void Resume()
    {
        if (!_paused) return;
        _paused = false;
        Log("Resumed — stream writing force packets again");
    }

    // ── Connect / init ────────────────────────────────────────────────────

    private bool ConnectAndStart()
    {
        // Re-entrancy guard: the pump thread may still be in the range wait
        // or init phase (IsInitialized not yet true) when a second
        // Initialize() arrives — treat the in-flight connect as success.
        if (_running && _pumpThread is { IsAlive: true })
        {
            Log("ConnectAndStart: connect already in progress — returning");
            return true;
        }

        Log("ConnectAndStart: enumerating HID devices (VID 046D)...");
        List<HidDeviceInfo> devices;
        try
        {
            devices = HidDeviceEnumerator.EnumerateByVid(LogitechVid);
        }
        catch (Exception ex)
        {
            LastError = $"HID enumeration failed: {ex.Message}";
            Log($"ConnectAndStart: enumeration FAILED: {ex.Message}");
            return false;
        }

        // The TrueForce stream is the 0xFFFD collection (interface 2,
        // endpoint 0x03 OUT, 64-byte reports). The HID++ control interface
        // (0xFF43) and joystick (0x0001) are handled elsewhere.
        var stream = devices
            .Where(d => SupportedPids.Contains(d.ProductId))
            .Where(d => d.UsagePage == 0xFFFD)
            .OrderByDescending(d => d.OutputReportByteLength)
            .FirstOrDefault();

        Log(stream != null
            ? $"ConnectAndStart: stream interface found: \"{stream.ProductString}\" PID=0x{stream.ProductId:X4} page=0x{stream.UsagePage:X4} inLen={stream.InputReportByteLength} outLen={stream.OutputReportByteLength} [{stream.DevicePath}]"
            : $"ConnectAndStart: NO TrueForce stream interface (0xFFFD) among {devices.Count} HID device(s)");

        if (stream == null || stream.OutputReportByteLength < PacketLen)
        {
            LastError = "No TrueForce stream interface found — the app falls back to DirectInput force";
            Log($"ConnectAndStart: FAILED — {LastError}");
            return false;
        }

        _devicePath = stream.DevicePath;
        _productName = stream.ProductString;

        _handle = CreateFile(_devicePath, GENERIC_WRITE | GENERIC_READ, FILE_SHARE_RW, IntPtr.Zero, OPEN_EXISTING, 0, IntPtr.Zero);
        if (_handle == InvalidHandle)
        {
            _handle = CreateFile(_devicePath, GENERIC_WRITE, FILE_SHARE_RW, IntPtr.Zero, OPEN_EXISTING, 0, IntPtr.Zero);
        }
        if (_handle == InvalidHandle)
        {
            LastError = $"TrueForce stream open FAILED (err={Marshal.GetLastWin32Error()}) — is another app streaming (G HUB / the game)?";
            Log($"ConnectAndStart: open FAILED — {LastError}");
            return false;
        }
        Log($"ConnectAndStart: opened stream interface \"{_productName}\" (outLen={stream.OutputReportByteLength})");

        _targetNorm = 0f;
        _smoothedLsb = 0f;
        _paused = false;
        _running = true;
        _pumpThread = new Thread(PumpLoop)
        {
            Name = "LogitechTrueForceStream",
            IsBackground = true,
            Priority = ThreadPriority.Highest
        };
        _pumpThread.Start();

        // IsInitialized flips true on the pump thread once the init
        // sequence completes (~300 ms after the range wait). Until then
        // the telemetry loop keeps using the DirectInput path.
        LastError = null;
        Log($"ConnectAndStart: handle open — pump thread starting (init waits up to {RangeWaitMs} ms for the range read, then streams at {StreamHz} Hz)");
        return true;
    }

    /// <summary>Replay the 68-packet G HUB init sequence twice, seq
    /// restarted at 1 each pass, 2 ms apart, range patched.</summary>
    private bool RunInitSequence()
    {
        Log($"RunInitSequence: 2 passes x {InitPacketCount} packets, {InitInterPacketUs / 1000.0:F0} ms apart (range={RotationDegrees}°)...");
        for (int pass = 0; pass < 2 && _running; pass++)
        {
            for (int i = 0; i < InitPacketCount && _running; i++)
            {
                byte[] pkt = InitPackets[i];
                pkt[SeqOffset] = (byte)((i + 1) & 0xFF);
                PatchRangePacket(pkt);

                if (!WritePacket(pkt))
                {
                    LastError = $"Init packet {i + 1} (pass {pass + 1}) write FAILED (err={Marshal.GetLastWin32Error()})";
                    Log($"RunInitSequence: FAILED at packet {i + 1} pass {pass + 1} — {LastError}");
                    return false;
                }
                PrecisionSleepUs(InitInterPacketUs);
            }
            Log($"RunInitSequence: pass {pass + 1} complete");
        }

        // Shutdown raced the init — abort so the pump exits promptly and never
        // replays the sequence after the teardown handshake has been sent.
        if (!_running)
        {
            Log("RunInitSequence: aborted (shutdown in progress)");
            return false;
        }

        _seq = (byte)((InitPacketCount + 1) & 0xFF);
        Log($"RunInitSequence: DONE — session seq starts at {_seq}");
        return true;
    }

    /// <summary>Rewrite the operating range a type-0x0e packet carries.
    /// The captured sequence pushes 2700° (whatever the wheel was set to
    /// when G HUB was recorded) — replayed verbatim it silently overwrites
    /// the user's range and the wheel sweeps to apply it. IEEE754 single,
    /// little-endian on the wire, exactly like the captured packet.</summary>
    private void PatchRangePacket(byte[] pkt)
    {
        if (pkt[TypeOffset] != RangeType) return;
        int rot = RotationDegrees;
        if (rot <= 0 || rot > 2700) return;

        uint bits = BitConverter.SingleToUInt32Bits((float)rot);
        pkt[RangeOffset + 0] = (byte)bits;
        pkt[RangeOffset + 1] = (byte)(bits >> 8);
        pkt[RangeOffset + 2] = (byte)(bits >> 16);
        pkt[RangeOffset + 3] = (byte)(bits >> 24);
        Log($"PatchRangePacket: type-0x0e range rewritten to {rot}° (was 2700° in the capture)");
    }

    // ── Stream pump ───────────────────────────────────────────────────────

    private void PumpLoop()
    {
        TimeBeginPeriod(1);
        try
        {
            // The HID++ settings read (parallel thread) reports the wheel's
            // real rotation within ~1-2 s of connect. Wait for it so the
            // type-0x0e init push carries the wheel's own range and is a
            // no-op instead of a sweep to the captured/default value.
            if (!WaitForRangeKnown(RangeWaitMs))
                Log($"PumpLoop: range not reported within {RangeWaitMs} ms — init will push the configured default ({_rotationDegrees}°)");

            if (!RunInitSequence())
            {
                LastError ??= "TrueForce init sequence failed";
                Log($"PumpLoop: init FAILED — {LastError}");
                IsInitialized = false;
                _running = false;
                if (_handle != InvalidHandle)
                {
                    CloseHandle(_handle);
                    _handle = InvalidHandle;
                }
                return;
            }

            IsInitialized = true;
            Log($"PumpLoop: stream active at {StreamHz} Hz — rotation={_rotationDegrees}°, invert={ForceInvert}, scale={ForceScale:F2}, smooth={SmoothTimeConstantMs:F1} ms");

            var sw = System.Diagnostics.Stopwatch.StartNew();
            long periodTicks = System.Diagnostics.Stopwatch.Frequency / StreamHz;
            long nextTick = sw.ElapsedTicks + periodTicks;

            while (_running)
            {
                try
                {
                    PumpTick();
                }
                catch (Exception ex)
                {
                    Log($"PumpLoop: tick exception — {ex.GetType().Name}: {ex.Message}");
                    Thread.Sleep(1);
                }

                long now = sw.ElapsedTicks;
                long remaining = nextTick - now;
                if (remaining > 0)
                {
                    long oneMsTicks = System.Diagnostics.Stopwatch.Frequency / 1000;
                    while (_running && (nextTick - sw.ElapsedTicks) > oneMsTicks)
                        Thread.Sleep(1);
                    while (_running && sw.ElapsedTicks < nextTick)
                        Thread.SpinWait(64);
                }
                nextTick += periodTicks;

                // Slipped more than one period (long stall): don't catch up
                // by burst-writing, emit one packet per loop iteration.
                if (sw.ElapsedTicks - nextTick > periodTicks)
                    nextTick = sw.ElapsedTicks + periodTicks;
            }
        }
        finally
        {
            TimeEndPeriod(1);
        }
        Log("PumpLoop: stopped");
    }

    private bool WaitForRangeKnown(int timeoutMs)
    {
        if (_rangeKnown) return true;
        var deadline = System.Diagnostics.Stopwatch.GetTimestamp() + (long)timeoutMs * System.Diagnostics.Stopwatch.Frequency / 1000;
        while (_running && !_rangeKnown && System.Diagnostics.Stopwatch.GetTimestamp() < deadline)
            Thread.Sleep(25);
        return _rangeKnown;
    }

    private byte[] _packetBuf = new byte[PacketLen];

    private void PumpTick()
    {
        if (_paused) return;

        Array.Clear(_packetBuf, 0, PacketLen);
        _packetBuf[0] = 0x01;
        _packetBuf[4] = 0x01;
        _packetBuf[5] = _seq++;

        float target = _targetNorm;
        if (ForceInvert) target = -target;
        if (ForceScale != 1.0f) target *= ForceScale;

        int t = (int)Math.Round(target * 32767f);
        t = Math.Clamp(t, -32768, 32767);

        float tau = SmoothTimeConstantMs;
        if (tau > 0f)
        {
            float alpha = 1f / (tau + 1f);
            _smoothedLsb = _smoothedLsb * (1f - alpha) + t * alpha;
            t = (int)Math.Round(_smoothedLsb);
        }
        else
        {
            _smoothedLsb = t;
        }

        ushort cur = (ushort)(t + 0x8000);
        _packetBuf[6] = (byte)(cur & 0xFF);
        _packetBuf[7] = (byte)(cur >> 8);
        _packetBuf[8] = (byte)(cur & 0xFF);
        _packetBuf[9] = (byte)(cur >> 8);
        // byte 10 = 0: pure force command; bytes 11-63 stay zero.

        if (!WritePacket(_packetBuf))
        {
            _consecutiveFails++;
            Interlocked.Increment(ref _packetsFailed);
            if (_consecutiveFails is 1 or 250)
                Log($"PumpTick: write FAILED ({_consecutiveFails} consecutive, err={Marshal.GetLastWin32Error()})");
            if (_consecutiveFails >= MaxConsecutiveWriteFails)
            {
                LastError = "TrueForce stream writes failed — wheel unplugged or interface lost";
                Log($"PumpTick: {MaxConsecutiveWriteFails} consecutive failures — stopping stream ({LastError})");
                IsInitialized = false;
                _running = false;
            }
            return;
        }

        _consecutiveFails = 0;
        long sent = Interlocked.Increment(ref _packetsSent);
        if (sent == 1 || sent % 500 == 0)
            Log($"PumpTick: #{sent} cur=0x{cur:X4} ({(target * 100f):+0.0;-0.0;0.0}%) paused={_paused}");
    }

    private void WriteNeutralPacket()
    {
        if (_handle == InvalidHandle) return;
        try
        {
            Array.Clear(_packetBuf, 0, PacketLen);
            _packetBuf[0] = 0x01;
            _packetBuf[4] = 0x01;
            _packetBuf[5] = _seq++;
            _packetBuf[6] = 0x00; _packetBuf[7] = 0x80;
            _packetBuf[8] = 0x00; _packetBuf[9] = 0x80;
            WritePacket(_packetBuf);
        }
        catch (Exception ex)
        {
            Log($"WriteNeutralPacket: threw — {ex.GetType().Name}: {ex.Message}");
        }
    }

    private bool WritePacket(byte[] pkt)
    {
        bool ok = WriteFile(_handle, pkt, PacketLen, out _, IntPtr.Zero);
        if (!ok)
            ok = HidD_SetOutputReport(_handle, pkt, PacketLen);
        return ok;
    }

    private void StopPump()
    {
        Log("StopStream: stopping pump");
        _running = false;
        // Join until the thread actually exits — a single short join can time
        // out while the pump is mid-init or blocked in a synchronous WriteFile,
        // and closing the handle under a live write is undefined behaviour.
        var t = _pumpThread;
        for (int i = 0; i < 20 && t?.IsAlive == true; i++)
            t.Join(250);
        _pumpThread = null;
    }

    private void CloseStreamHandle()
    {
        if (_handle != InvalidHandle)
        {
            CloseHandle(_handle);
            _handle = InvalidHandle;
        }
        Log("StopStream: done");
    }

