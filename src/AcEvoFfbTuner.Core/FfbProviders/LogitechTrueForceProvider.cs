    }

    private static void PrecisionSleepUs(int microseconds)
    {
        if (microseconds <= 0) return;
        long target = System.Diagnostics.Stopwatch.GetTimestamp() + (System.Diagnostics.Stopwatch.Frequency * microseconds) / 1_000_000L;
        int ms = microseconds / 1000;
        if (ms > 0) Thread.Sleep(ms);
        while (System.Diagnostics.Stopwatch.GetTimestamp() < target) Thread.SpinWait(32);
    }
